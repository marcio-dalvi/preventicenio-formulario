// Usa Playwright já instalado na máquina; caminho do módulo informado como argumento.
import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.argv[2]);
const output = 'test-results';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  let mode = 'ok';
  await page.route('https://viacep.com.br/**', async route => {
    if (mode === 'offline') return route.abort();
    if (mode === 'slow') await new Promise(resolve => setTimeout(resolve, 1200));
    await route.fulfill({ json: mode === 'missing' ? { erro: true } : { logradouro: 'Praça da Sé', bairro: 'Sé', localidade: 'São Paulo', uf: 'SP' } });
  });
  assert.equal((await page.goto('http://127.0.0.1:3000')).status(), 200);
  await page.evaluate(() => document.fonts.ready);
  assert.match(await page.title(), /Prevent Senior/);
  assert.equal(await page.locator('.brand-logo').getAttribute('alt'), 'Prevent Senior');
  assert.ok(await page.locator('.brand-logo').evaluate(img => img.complete && img.naturalWidth > 0));
  assert.ok(await page.evaluate(() => document.fonts.check('400 14px Poppins')));
  assert.match(await page.locator('body').innerText(), /Prevent Senior/);
  assert.doesNotMatch(await page.locator('body').innerText(), /Preventicênio/i);
  assert.equal(await page.locator('button').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(24, 76, 160)');
  console.log('PASS: título, logo oficial carregado, fonte Poppins local e azul #184ca0; marca antiga ausente.');
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: true });
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  assert.ok(await page.locator('[aria-invalid=true]').count() >= 15);
  console.log('PASS: campos obrigatórios bloqueiam download e exibem erros.');
  const fill = (name, value) => page.locator(`[name=${name}]`).fill(value);
  for (const [name, value] of Object.entries({ nome: 'Empresa Demonstração', documento: '11222333000181', numero: '100', telefone: '11999999999', email: 'cadastro@example.com', responsavelNome: 'Pessoa Exemplo', responsavelEmail: 'legal@example.com', responsavelTelefone: '1133334444', financeiroNome: 'Pessoa Financeiro', financeiroEmail: 'financeiro@example.com', financeiroTelefone: '11988888888', tecnicoNome: 'Pessoa Técnico', tecnicoEmail: 'tecnico@example.com', tecnicoTelefone: '11977777777' })) await fill(name, value);
  await fill('cep', '01001000');
  await page.getByText('Endereço encontrado. Confira os dados e informe o número.').waitFor();
  assert.equal(await page.locator('[name=cidade]').inputValue(), 'São Paulo');
  assert.equal(await page.locator('[name=telefone]').inputValue(), '(11) 99999-9999');
  console.log('PASS: ViaCEP preenche logradouro/bairro/cidade/UF; máscara de telefone aplicada.');
  await fill('documento', '11222333000182');
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  assert.equal(await page.locator('[name=documento]').getAttribute('aria-invalid'), 'true');
  await fill('documento', '11222333000181');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'preventsenior-cadastro.json');
  await download.saveAs(`${output}/cadastro-pj.json`);
  const data = JSON.parse(await readFile(`${output}/cadastro-pj.json`, 'utf8'));
  assert.equal(data.documento, '11222333000181');
  assert.equal(data.contatoFinanceiro.email, 'financeiro@example.com');
  assert.equal(data.endereco.uf, 'SP');
  assert.equal(data.simulacao, true);
  console.log('PASS: CNPJ inválido bloqueado; JSON PJ baixado e conteúdo conferido.');
  await page.locator('[name=tipo][value=pf]').check();
  assert.equal(await page.locator('#document-label').textContent(), 'CPF *');
  assert.equal(await page.locator('#registration-label').textContent(), 'RG');
  await fill('nome', 'Pessoa Demonstração');
  await fill('documento', '52998224725');
  const pfPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  await (await pfPromise).saveAs(`${output}/cadastro-pf.json`);
  assert.equal(JSON.parse(await readFile(`${output}/cadastro-pf.json`, 'utf8')).tipoPessoa, 'pf');
  console.log('PASS: troca PF, rótulos CPF/RG e download JSON PF.');
  mode = 'missing';
  await fill('cep', '99999999');
  await page.getByText('CEP não encontrado. Confira os números.').waitFor();
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  assert.equal(await page.locator('[name=cep]').getAttribute('aria-invalid'), 'true');
  console.log('PASS: CEP inexistente bloqueia salvamento.');
  mode = 'offline';
  await fill('cep', '01001000');
  await page.getByText('Consulta indisponível. Preencha o endereço manualmente.').waitFor();
  console.log('PASS: falha de rede mantém preenchimento manual disponível.');
  mode = 'slow';
  await fill('cep', '01001001');
  await page.getByRole('button', { name: 'Salvar cadastro' }).click();
  assert.match(await page.locator('#result').textContent(), /Aguarde/);
  await page.getByText('Endereço encontrado. Confira os dados e informe o número.').waitFor();
  console.log('PASS: consulta CEP pendente bloqueia salvamento prematuro.');
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow em ${width}px`);
    await page.screenshot({ path: `${output}/mobile-${width}.png`, fullPage: true });
  }
  assert.deepEqual(errors, []);
  console.log('PASS: responsivo 390px e 320px, sem overflow horizontal; zero erros JavaScript.');
  console.log('Evidências: test-results/desktop.png, mobile-390.png, mobile-320.png, cadastro-pj.json, cadastro-pf.json');
} finally { await browser.close(); }
